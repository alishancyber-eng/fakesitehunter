def _decode_unicode_to_ascii(text: str) -> str:
    result = []
    for c in text:
        if c in _UNICODE_TO_LATIN: result.append(_UNICODE_TO_LATIN[c])
        elif ord(c) < 128: result.append(c)
        else:
            decomp = unicodedata.normalize("NFKD", c)
            ap = "".join(ch for ch in decomp if ord(ch) < 128)
            if ap: result.append(ap)
    return "".join(result).lower()

def _decode_punycode_label(label: str) -> str:
    if not label.lower().startswith("xn--"): return label.lower()
    try:
        uf = label.encode("ascii").decode("idna")
        return _decode_unicode_to_ascii(uf)
    except Exception:
        try:
            uf = label[4:].encode("ascii").decode("punycode")
            return _decode_unicode_to_ascii(uf)
        except Exception: return label.lower()


