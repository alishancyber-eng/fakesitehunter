# CELL 7 — pipeline_scan() (SERVER)
# Main detection function — Flask API isko call karega
# Returns: (verdict, confidence, engines_used)
# ════════════════════════════════════════════════════════════════

def pipeline_scan(url):
    t0 = time.time()
    driver = None

    # ── Stage 1: Engine 1 (no browser) ──────────────────────────
    e1_result = predictor.predict(url)
    e1_route   = e1_result['decision_path']
    e1_conf    = e1_result['confidence']
    e1_phish   = e1_result['is_phish']

    # E1 PHISHING → EXIT
    if e1_phish:
        verdict    = "PHISHING"
        confidence = e1_conf * 100
        record_scan(url, verdict, "E1")
        return verdict, confidence, "E1"

    # E1 LEGITIMATE → proceed to E2
    # ── Stage 2: Engine 2 (browser required) ────────────────────
    browser_url = url if url.startswith(('http://', 'https://')) else 'https://' + url

    try:
        driver = create_driver()
        driver.set_page_load_timeout(25)
        driver.get(browser_url)
        try:
            WebDriverWait(driver, 15).until(
                lambda d: d.execute_script("return document.readyState") == "complete"
            )
        except TimeoutException:
            pass
        time.sleep(1.5)
        final_url = driver.current_url

    except Exception:
        if driver:
            try: driver.quit()
            except: pass
        record_scan(url, "LINK DOES NOT EXIST", "ERROR")
        return "LINK DOES NOT EXIST", 0, "ERROR"

    # ML prediction
    features = {**extract_url_features(final_url), **extract_html_features(driver)}
    X_input  = e2_scaler.transform(features_to_array(features))
    ml_proba = e2_ml_model.predict_proba(X_input)[0]
    ml_score = ml_proba[1] * 100

    # NLP analysis
    nlp_score, nlp_findings = nlp_analysis(driver, final_url)

    # Tranco / hosting check
    final_hostname = (urlparse(final_url).hostname or "").lower()
    is_hosting = any(final_hostname.endswith(h) for h in UNTRUSTED_HOSTING)
    is_trusted = False
    if not is_hosting:
        is_trusted = e2_is_tranco_domain(url) or e2_is_tranco_domain(final_url)

    # E2 decision logic
    if nlp_score >= 25:
        combined   = (0.40 * ml_score) + (0.60 * nlp_score)
        if is_trusted and nlp_score < 40:
            e2_verdict = "LEGITIMATE"
        else:
            e2_verdict = "PHISHING" if combined > 35 else "LEGITIMATE"
    elif nlp_score > 0 and ml_score > 60:
        combined   = (0.50 * ml_score) + (0.50 * nlp_score)
        if is_trusted:
            e2_verdict = "LEGITIMATE"
        else:
            e2_verdict = "PHISHING" if combined > 50 else "LEGITIMATE"
    elif is_trusted:
        combined   = ml_score * 0.3
        e2_verdict = "LEGITIMATE"
    elif is_hosting:
        combined   = ml_score
        e2_verdict = "PHISHING" if combined > 60 else "LEGITIMATE"
    else:
        combined   = ml_score
        e2_verdict = "PHISHING" if combined > 75 else "LEGITIMATE"

    combined = max(0, min(combined, 100))
    e2_confidence = combined if e2_verdict == "PHISHING" else 100 - combined

    # E2 PHISHING → EXIT
    if e2_verdict == "PHISHING":
        try: driver.quit()
        except: pass
        record_scan(url, "PHISHING", "E1->E2")
        return "PHISHING", e2_confidence, "E1->E2"

    # E2 LEGITIMATE with confidence >= 55% → EXIT
    if e2_verdict == "LEGITIMATE" and e2_confidence >= 55:
        try: driver.quit()
        except: pass
        record_scan(url, "LEGITIMATE", "E1->E2")
        return "LEGITIMATE", e2_confidence, "E1->E2"

    # E2 uncertain (< 55%) → Engine 3
    # ── Stage 3: Engine 3 (same browser session) ─────────────────
    shot_path = "/tmp/pipeline_shot.png"

    # Dismiss popups
    try:
        driver.execute_script("""
            var buttons = document.querySelectorAll('button, a, div[role="button"]');
            for(var b of buttons){
                var t = b.innerText.toLowerCase();
                if(t.includes('accept')||t.includes('agree')||t.includes('allow')
                   ||t.includes('consent')||t.includes('ok')||t.includes('got it')){
                    b.click(); break;
                }
            }
        """)
        time.sleep(1)
    except Exception:
        pass

    driver.save_screenshot(shot_path)
    try: driver.quit()
    except: pass

    # Screenshot fallback
    if not os.path.exists(shot_path) or os.path.getsize(shot_path) < 1000:
        record_scan(url, e2_verdict, "E1->E2-fallback")
        return e2_verdict, e2_confidence, "E1->E2-fallback"

    # CNN prediction
    img    = Image.open(shot_path).convert('RGB')
    tensor = e3_eval_transform(img).unsqueeze(0).to(DEVICE)
    e3_model.eval()
    with torch.no_grad():
        output = e3_model(tensor)
        prob   = torch.nn.functional.softmax(output, dim=1)
    phish_prob = prob[0][1].item() * 100

    # Final: E2 x 50% + E3 x 50%
    final_phish = (0.50 * combined) + (0.50 * phish_prob)

    if final_phish >= 50:
        verdict    = "PHISHING"
        confidence = final_phish
    else:
        verdict    = "LEGITIMATE"
        confidence = 100 - final_phish

    record_scan(url, verdict, "E1->E2->E3")
    return verdict, confidence, "E1->E2->E3"

