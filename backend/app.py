def e2_is_tranco_domain(url):
    if not e2_tranco_domains:
        return False

    hostname = (urlparse(url).hostname or "").lower()

    for h in TRANCO_HOSTING_OVERRIDE:
        if hostname.endswith(h):
            return False

    brand_fake = re.match(r'^(www\.)?([a-z]+)\.com\.[a-z]{2,3}$', hostname)
    if brand_fake:
        brand_name = brand_fake.group(2)
        real_domain = brand_name + '.com'
        if real_domain in e2_tranco_domains and real_domain != hostname:
            return False

    parts = hostname.split('.')
    if len(parts) >= 3:
        base2 = '.'.join(parts[-2:])
        base3 = '.'.join(parts[-3:]) if len(parts) >= 3 else ""
        for h in TRANCO_HOSTING_OVERRIDE:
            if base2 == h or base3 == h:
                return False

    if hostname in e2_tranco_domains:
        return True
    for i in range(len(parts)):
        domain = '.'.join(parts[i:])
        if domain in e2_tranco_domains:
            return True
    return False


# URL Feature Extraction

def extract_url_features(url):
    features = {}
    parsed = urlparse(url)
    hostname = parsed.hostname or ""
    path = parsed.path or ""
    full_url = url.lower()

    shorteners = ['bit.ly','tinyurl.com','goo.gl','t.co','ow.ly','short.link',
                  'tiny.cc','is.gd','buff.ly','rebrand.ly','cutt.ly','rb.gy']

    features['length_url'] = len(url)
    features['length_hostname'] = len(hostname)
    features['ip'] = 1 if re.match(r'^\d{1,3}(\.\d{1,3}){3}$', hostname) else 0

    for char, name in [('.','nb_dots'),('-','nb_hyphens'),('@','nb_at'),('?','nb_qm'),
                       ('&','nb_and'),('|','nb_or'),('=','nb_eq'),('_','nb_underscore'),
                       ('~','nb_tilde'),('%','nb_percent'),('/','nb_slash'),('*','nb_star'),
                       (':','nb_colon'),(',','nb_comma'),(';','nb_semicolumn'),('$','nb_dollar')]:
        features[name] = url.count(char)

    features['nb_space'] = url.count(' ') + url.count('%20')
    features['nb_www'] = full_url.count('www')
    features['nb_com'] = full_url.count('.com')
    features['nb_dslash'] = url.count('//')
    features['http_in_path'] = 1 if 'http' in path.lower() else 0
    features['https_token'] = 1 if parsed.scheme == 'https' else 0
    features['ratio_digits_url'] = sum(c.isdigit() for c in url) / max(len(url), 1)
    features['ratio_digits_host'] = sum(c.isdigit() for c in hostname) / max(len(hostname), 1)
    features['punycode'] = 1 if 'xn--' in hostname.lower() else 0
    features['port'] = 1 if parsed.port and parsed.port not in [80, 443] else 0

    tld_re = r'\.(com|net|org|gov|edu|io|co)\/'
    features['tld_in_path'] = 1 if re.search(tld_re, path.lower()) else 0

    sub_parts = hostname.split('.')[:-2] if hostname.count('.') >= 2 else []
    subdomain = '.'.join(sub_parts)
    features['tld_in_subdomain'] = 1 if re.search(tld_re, subdomain.lower()) else 0
    features['abnormal_subdomain'] = 1 if len(sub_parts) > 2 else 0
    features['nb_subdomains'] = len(sub_parts)
    features['prefix_suffix'] = 1 if '-' in hostname else 0

    domain_name = hostname.split('.')[0] if hostname else ''
    consonants = sum(1 for c in domain_name.lower() if c in 'bcdfghjklmnpqrstvwxyz')
    vowels_ct = sum(1 for c in domain_name.lower() if c in 'aeiou')
    features['random_domain'] = 1 if consonants / (vowels_ct + 1) > 4 else 0
    features['shortening_service'] = 1 if any(s in hostname.lower() for s in shorteners) else 0

    sus_ext = ['.php','.html','.asp','.aspx','.jsp','.cgi']
    features['path_extension'] = 1 if any(path.lower().endswith(e) for e in sus_ext) else 0
    features['nb_redirection'] = url.count('//')
    features['nb_external_redirection'] = 1 if 'redirect' in full_url or 'redir' in full_url else 0

    sep = re.compile(r'[\-\_\.\/?=&@%\+\|#~,;:!\*\(\)\[\]]')
    words_raw = [w for w in sep.split(url) if w and len(w) > 1]
    if words_raw:
        wl = [len(w) for w in words_raw]
        features['length_words_raw'] = len(words_raw)
        features['shortest_words_raw'] = min(wl)
        features['longest_words_raw'] = max(wl)
    else:
        features['length_words_raw'] = 0
        features['shortest_words_raw'] = 0
        features['longest_words_raw'] = 0

    max_rep, cur_rep = 1, 1
    for i in range(1, len(url)):
        if url[i] == url[i-1]:
            cur_rep += 1; max_rep = max(max_rep, cur_rep)
        else:
            cur_rep = 1
    features['char_repeat'] = max_rep

    for part, prefix in [(hostname, 'host'), (path, 'path')]:
        pw = [w for w in sep.split(part) if w and len(w) > 1]
        if pw:
            pl = [len(w) for w in pw]
            features[f'shortest_word_{prefix}'] = min(pl)
            features[f'longest_word_{prefix}'] = max(pl)
        else:
            features[f'shortest_word_{prefix}'] = 0
            features[f'longest_word_{prefix}'] = 0

    return features


