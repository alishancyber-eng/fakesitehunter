# Engine 3 Detection Function

def engine3_detect(screenshot_path):
    t0 = time.time()

    try:
        img = Image.open(screenshot_path).convert('RGB')
        tensor = e3_eval_transform(img).unsqueeze(0).to(DEVICE)

        e3_model.eval()
        with torch.no_grad():
            output = e3_model(tensor)
            prob = torch.nn.functional.softmax(output, dim=1)
            conf_val, pred_idx = torch.max(prob, 1)

        result = E3_CLASSES[pred_idx.item()]
        confidence = conf_val.item() * 100
        legit_prob = prob[0][0].item() * 100
        phish_prob = prob[0][1].item() * 100

        verdict = "PHISHING" if result == "phishing" else "LEGITIMATE"
        elapsed = time.time() - t0

        return verdict, confidence, {
            'prediction': result,
            'confidence': confidence,
            'legit_prob': legit_prob,
            'phish_prob': phish_prob,
            'elapsed_s': elapsed,
        }

    except Exception as e:
        return "LEGITIMATE", 50.0, {
            'prediction': 'error',
            'confidence': 50.0,
            'legit_prob': 50.0,
            'phish_prob': 50.0,
            'elapsed_s': time.time() - t0,
            'error': str(e),
        }

