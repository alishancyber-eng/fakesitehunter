# Decode Engine (Leet, Case Confusable, Compression)

LEET_MAP: Dict[str,str] = {
    "0":"o","1":"l","2":"z","3":"e","4":"a","5":"s",
    "6":"b","7":"t","8":"b","9":"g","@":"a","$":"s","!":"i","|":"l","+":"t"}
LEET_MULTI: Dict[str,List[str]] = {
    "1":["l","i"],"0":["o"],"3":["e"],"4":["a"],"5":["s"],"7":["t"],"9":["g"]}
CASE_CONFUSABLE: Dict[str,str] = {"I":"l","O":"o"}
COMPRESS_PAIRS: Dict[str,str] = {"rn":"m","cl":"d","vv":"w"}

MULTI_DECODE_MAX_AMBIG = 5

def _apply_leet_single(t):
    return "".join(LEET_MAP.get(c,c) for c in t.lower())
def _apply_case_confusable(t):
    return "".join(CASE_CONFUSABLE.get(c,c) for c in t)
def _apply_compress(t):
    r=t
    for p,rep in COMPRESS_PAIRS.items(): r=r.replace(p,rep)
    return r

def _generate_multi_variants(text: str) -> Set[str]:
    lower=text.lower()
    ambig=[(i,LEET_MULTI[c]) for i,c in enumerate(lower)
           if c in LEET_MULTI and len(LEET_MULTI[c])>1]
    if not ambig: return set()
    if len(ambig)>MULTI_DECODE_MAX_AMBIG:
        vs=set(); base=list(_apply_leet_single(lower))
        for pos,opts in ambig:
            for o in opts: v=base.copy(); v[pos]=o; vs.add("".join(v))
        return vs
    vs=set(); n=len(ambig)
    for mask in range(1<<n):
        chars=list(lower)
        for bit,(pos,opts) in enumerate(ambig):
            chars[pos]=opts[1] if (mask&(1<<bit)) else opts[0]
        result=[]
        for j,c in enumerate(chars):
            if c==lower[j] and c in LEET_MAP and c not in LEET_MULTI:
                result.append(LEET_MAP[c])
            else: result.append(c)
        vs.add("".join(result))
    return vs

@functools.lru_cache(maxsize=16384)
def full_decode(text: str) -> FrozenSet[str]:
    original=text.lower()
    ca=_apply_case_confusable(text).lower()
    la=_apply_leet_single(text); cl=_apply_leet_single(ca)
    mr=_generate_multi_variants(text); mc=_generate_multi_variants(ca)
    intermediates={ca,la,cl}|mr|mc
    compressed=set()
    for form in intermediates:
        c=_apply_compress(form)
        if c!=form: compressed.add(c)
    compressed.add(_apply_leet_single(_apply_compress(original)))
    all_forms=intermediates|compressed; all_forms.discard(original)
    return frozenset(all_forms)

def count_substitutions(orig,dec):
    if len(orig)==len(dec):
        return sum(1 for a,b in zip(orig.lower(),dec) if a!=b)
    return abs(len(orig)-len(dec))

def _leet_position_entropy(dl: str) -> float:
    pos=[i for i,c in enumerate(dl) if c in LEET_MAP]
    if len(pos)<=1: return 0.0
    n=len(dl)
    if n==0: return 0.0
    bins=[0]*5
    for p in pos: bins[min(int(p/n*5),4)]+=1
    total=sum(bins)
    if total==0: return 0.0
    ent=0.0
    for b in bins:
        if b>0: r=b/total; ent-=r*math.log2(r)
    return ent


