# Model Architecture

class PhishDetector(nn.Module):
    def __init__(self):
        super().__init__()
        self.net = EfficientNet.from_name('efficientnet-b0')
        for p in list(self.net.parameters())[:-30]:
            p.requires_grad = False
        inf = self.net._fc.in_features
        self.net._fc = nn.Sequential(
            nn.Dropout(0.4),
            nn.Linear(inf, 512),
            nn.ReLU(),
            nn.BatchNorm1d(512),
            nn.Dropout(0.2),
            nn.Linear(512, 2)
        )
    def forward(self, x):
        return self.net(x)


