class IDNAResult(NamedTuple):
    is_valid:bool; failure_reason:str; is_suspicious:bool; ace_form:str

def validate_idna2008(domain: str) -> IDNAResult:
    if not IDNA_AVAILABLE: return IDNAResult(True,"",False,"")
    try:
        normalized=unicodedata.normalize("NFC",domain.lower())
        labels=normalized.split(".")
        ace=[]
        for label in labels:
            if not label: continue
            if all(ord(c)<128 for c in label): ace.append(label); continue
            try:
                enc=idna_lib.encode(label, uts46=False)
                ace.append(enc.decode("ascii").rstrip("."))
            except (idna_lib.core.InvalidCodepoint,
                    idna_lib.core.InvalidCodepointContext) as e:
                return IDNAResult(False,f"Invalid: {str(e)[:80]}",True,"")
            except (idna_lib.core.IDNAError,UnicodeError) as e:
                return IDNAResult(False,f"IDNA fail: {str(e)[:80]}",True,"")
        af=".".join(ace) if ace else ""
        sus=False
        for label in labels:
            if not label: continue
            hl=any(c.isascii() and c.isalpha() for c in label)
            hn=any(ord(c)>=128 and unicodedata.category(c).startswith("L") for c in label)
            if hl and hn: sus=True; break
        return IDNAResult(True,"",sus,af)
    except Exception as e:
        return IDNAResult(False,f"Error: {str(e)[:60]}",True,"")

