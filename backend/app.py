class CharTokenizer:
    PAD, UNK, BOS, EOS = 0, 1, 2, 3
    SPECIAL = 4

    def __init__(self, max_len: int = 200, vocab_size: int = 512):
        self.max_len = max_len
        self.vocab_size = vocab_size
        self.c2i: Dict[str, int] = {}
        self.actual_vs: int = self.SPECIAL

    def encode(self, url: str) -> np.ndarray:
        ids = [self.BOS]
        for c in url[:self.max_len - 2]:
            ids.append(self.c2i.get(c, self.UNK))
        ids.append(self.EOS)
        ids += [self.PAD] * (self.max_len - len(ids))
        return np.array(ids[:self.max_len], dtype=np.int64)

    @classmethod
    def load_from_file(cls, path: str) -> 'CharTokenizer':
        with open(path, "r", encoding="utf-8") as f:
            data = json.load(f)
        t = cls(data["max_len"], data["vocab_size"])
        t.c2i = data["c2i"]
        t.actual_vs = data["actual_vs"]
        return t

