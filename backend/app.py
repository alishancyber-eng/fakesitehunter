THRESH_MODEL_ONLY = 0.50
THRESH_ASCII_ZD   = 0.40
THRESH_ENGLISH    = 0.88

def get_threshold_for_route(route, domain_length):
    base = {"ascii_zd": THRESH_ASCII_ZD, "english": THRESH_ENGLISH,
            "model": THRESH_MODEL_ONLY}.get(route, THRESH_MODEL_ONLY)
    if domain_length <= 6: base += 0.05
    elif domain_length >= 15: base -= 0.05
    return max(0.05, min(base, 0.99))


