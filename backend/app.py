    X_input = e2_scaler.transform(features_to_array(features))
    ml_proba = e2_ml_model.predict_proba(X_input)[0]
    ml_score = ml_proba[1] * 100

    nlp_score, nlp_findings = nlp_analysis(driver, final_url)

    final_hostname = (urlparse(final_url).hostname or "").lower()
    is_hosting = any(final_hostname.endswith(h) for h in UNTRUSTED_HOSTING)
    is_forsale = any(h in final_url.lower() for h in FORSALE_INDICATORS)

    is_trusted = False
    if not is_hosting and not is_forsale:
        is_trusted = e2_is_tranco_domain(url) or e2_is_tranco_domain(final_url)

    if nlp_score >= 25:
        combined = (0.40 * ml_score) + (0.60 * nlp_score)
        if is_trusted and nlp_score < 40:
            verdict = "LEGITIMATE"
        else:
            verdict = "PHISHING" if combined > 35 else "LEGITIMATE"
        method = "NLP-led"

    elif nlp_score > 0 and ml_score > 60:
        combined = (0.50 * ml_score) + (0.50 * nlp_score)
        if is_trusted:
            verdict = "LEGITIMATE"
        else:
            verdict = "PHISHING" if combined > 50 else "LEGITIMATE"
        method = "balanced"

    elif is_trusted:
        combined = ml_score * 0.3
        verdict = "LEGITIMATE"
        method = "Tranco-verified"

    elif is_hosting:
        combined = ml_score
        verdict = "PHISHING" if combined > 60 else "LEGITIMATE"
        method = "ML-hosting"

    elif is_forsale:
        combined = ml_score
        verdict = "PHISHING" if combined > 50 else "LEGITIMATE"
        method = "ML-forsale"

    else:
        combined = ml_score
        verdict = "PHISHING" if combined > 75 else "LEGITIMATE"
        method = "ML-only"

    combined = max(0, min(combined, 100))
    elapsed = time.time() - t0

    if verdict == "PHISHING":
        confidence = combined
    else:
        confidence = 100 - combined

    return verdict, confidence, {
        'ml_score': ml_score,
        'nlp_score': nlp_score,
        'nlp_findings': nlp_findings,
        'is_trusted': is_trusted,
        'is_hosting': is_hosting,
        'is_forsale': is_forsale,
        'method': method,
        'confidence': confidence,
        'combined_score': combined,
        'final_url': final_url,
        'elapsed_s': elapsed,
    }

