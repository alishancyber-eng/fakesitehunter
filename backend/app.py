class HomographNet(nn.Module):
    """CNN(k3+k5) -> BiGRU(64x2) -> Transformer(4h,1L) + Feature FC."""

    def __init__(self, vocab_size: int):
        super().__init__()
        self.embed = nn.Embedding(vocab_size, _E1_EMBED_DIM, padding_idx=0)
        self.embed_drop = nn.Dropout(_E1_DROPOUT)

        self.conv1 = nn.Conv1d(_E1_EMBED_DIM, _E1_CNN_FILTERS, 3, padding=1)
        self.conv2 = nn.Conv1d(_E1_CNN_FILTERS, _E1_CNN_FILTERS, 5, padding=2)
        self.conv_bn = nn.BatchNorm1d(_E1_CNN_FILTERS)
        self.conv_drop = nn.Dropout(_E1_DROPOUT)

        self.gru = nn.GRU(_E1_CNN_FILTERS, _E1_GRU_HIDDEN,
                          batch_first=True, bidirectional=True)
        self.gru_drop = nn.Dropout(_E1_DROPOUT)

        gru_out = _E1_GRU_HIDDEN * 2
        enc_layer = nn.TransformerEncoderLayer(
            d_model=gru_out, nhead=_E1_TFM_HEADS,
            dim_feedforward=_E1_TFM_FF, dropout=_E1_DROPOUT,
            batch_first=True)
        self.transformer = nn.TransformerEncoder(enc_layer, num_layers=_E1_TFM_LAYERS)

        self.feat_fc = nn.Sequential(
            nn.Linear(NUM_FEATURES, 32),
            nn.ReLU(),
            nn.Dropout(_E1_DROPOUT),
        )

        self.head = nn.Sequential(
            nn.Linear(gru_out + 32, 64),
            nn.ReLU(),
            nn.Dropout(_E1_DROPOUT),
            nn.Linear(64, 1),
        )

    def forward(self, tok: torch.Tensor, feat: torch.Tensor) -> torch.Tensor:
        x = self.embed_drop(self.embed(tok))
        x = x.transpose(1, 2)
        x = F_t.relu(self.conv1(x))
        x = F_t.relu(self.conv2(x))
        x = self.conv_drop(self.conv_bn(x))
        x = x.transpose(1, 2)
        x, _ = self.gru(x)
        x = self.gru_drop(x)
        x = self.transformer(x)
        x = x.mean(dim=1) + x.max(dim=1).values

        f = self.feat_fc(feat)
        return self.head(torch.cat([x, f], dim=1)).squeeze(-1)

